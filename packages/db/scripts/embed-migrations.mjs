// Writes src/migrations.generated.ts: every drizzle migration's SQL, sha256 and journal time, so
// the app can apply pending migrations from a serverless function (no files on disk at runtime).
// Run after `drizzle-kit generate` (the package "generate" script does both).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../drizzle/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", dir), "utf8"));
const entries = journal.entries.map((e) => {
  const sql = readFileSync(new URL(`${e.tag}.sql`, dir), "utf8");
  return { tag: e.tag, when: e.when, hash: createHash("sha256").update(sql).digest("hex"), sql };
});
const out = `// Generated by scripts/embed-migrations.mjs. Do not edit.\nexport const MIGRATIONS: { tag: string; when: number; hash: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(new URL("../src/migrations.generated.ts", import.meta.url), out);
console.log(`embedded ${entries.length} migrations`);
