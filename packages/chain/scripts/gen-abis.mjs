// Regenerates src/abis.ts from Foundry build output. Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../../contracts/out");
const contracts = [
  ["NorthesideMatchweeks.sol/NorthesideMatchweeks.json", "matchweeksAbi"],
  ["HostRewards.sol/HostRewards.json", "hostRewardsAbi"],
  ["IdentityAdapter.sol/IdentityAdapter.json", "identityAbi"],
];
let src = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit by hand.\n\n";
for (const [file, name] of contracts) {
  const { abi } = JSON.parse(readFileSync(join(out, file), "utf8"));
  src += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
src += `export const erc20Abi = [
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "spender", type: "address" }, { name: "amount", type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "owner", type: "address" }, { name: "spender", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "transfer", stateMutability: "nonpayable", inputs: [{ name: "to", type: "address" }, { name: "amount", type: "uint256" }], outputs: [{ type: "bool" }] },
] as const;
`;
writeFileSync(join(here, "../src/abis.ts"), src);
console.log("wrote src/abis.ts");
